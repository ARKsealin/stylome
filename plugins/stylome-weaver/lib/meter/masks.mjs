/** 一组词里出现的单字，各自的遮蔽词合并成一张表。同字规则一致，并集不会互相误挡。 */
export function masksFor(words, table) {
  const out = {}
  for (const w of words) {
    if (w.length !== 1 || !table[w]) continue
    out[w] = table[w]
  }
  return out
}

