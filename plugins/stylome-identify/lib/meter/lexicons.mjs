import { scanHits } from './scan.mjs'
import { LEXICON_CHAR_MASKS, masksFor } from './masks.mjs'

export const EMOTIONS = ['joy', 'like', 'anger', 'sorrow', 'fear', 'disgust', 'surprise']

/**
 * 一段文字里某个词表的命中次数。长词优先，命中处不再计数。
 * masked 为 false 时只做字面扫描：人称代词与术语计数用这条，遮蔽会把“我们”里的“我”挡掉。
 */
export function countLexicon(text, words, { masked = true } = {}) {
  const masks = masked ? masksFor(words, LEXICON_CHAR_MASKS) : {}
  let n = 0
  for (const pos of scanHits(text, words, masks).values()) n += pos.length
  return n
}

/** 全部词表的每千字频率。extra 是用户追加的词，按词表名合并。 */
export function lexiconRates(text, chars, extra = {}) {
  const scale = chars > 0 ? 1000 / chars : 0
  const out = {}
  for (const [name, words] of Object.entries(LEXICONS)) out[name] = countLexicon(text, [...words, ...(extra[name] ?? [])]) * scale
  return out
}
